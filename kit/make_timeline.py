"""Builds a film's timeline.js (caption timing) from the narration's word timestamps.

usage: python3 kit/make_timeline.py films/<slug> <film_duration_s> [narration_offset_s=0.25]

Reads from the film folder:
  words.json    [[word, start_s, end_s], ...] from transcribing vo.wav with word timestamps
                (objects with word/text and start_ms/end_ms or start/end are accepted too)
  captions.txt  one caption chunk per line: the same words in the same order, spelled the way they should appear
                on screen (2-5 words a line, broken where a reader would pause; a line may be a single word)
Writes timeline.js with FILM_DUR, WT (one [start, end] per word, in film seconds) and CH (the chunks).
"""
import json, sys
from pathlib import Path


def load_words(p):
    out = []
    for w in json.loads(p.read_text()):
        if isinstance(w, dict):
            word = w.get("word") or w.get("text")
            a = w["start_ms"] / 1000 if "start_ms" in w else w["start"]
            b = w["end_ms"] / 1000 if "end_ms" in w else w["end"]
        else:
            word, a, b = w
        out.append([word, float(a), float(b)])
    return out


def main(film, dur, off):
    words = load_words(film / "words.json")
    chunks = [ln.split() for ln in (film / "captions.txt").read_text().splitlines() if ln.strip()]
    tokens = [t for c in chunks for t in c]
    if len(tokens) != len(words):
        print(f"captions.txt has {len(tokens)} words, the transcript has {len(words)}. Side by side:")
        for i in range(max(len(tokens), len(words))):
            print(f"{i:4d}  {tokens[i] if i < len(tokens) else '-':18s} {words[i][0] if i < len(words) else '-'}")
        raise SystemExit(1)
    wt = []
    for _, a, b in words:
        a, b = round(a + off, 2), round(b + off, 2)
        if b - a < 0.08:
            b = round(a + 0.08, 2)
        wt.append([a, b])
    if wt[0][0] < 1.2:
        wt[0][0] = -0.1                       # the first caption is already on screen in frame 0 (it is the cover frame)
    if wt[-1][1] > dur - 1.3:
        print(f"warning: the narration ends at {wt[-1][1]}s; the caption tape leaves at {dur - 1.3}s")
    ch, k = [], 0
    for c in chunks:
        ch.append([[t, k + i] for i, t in enumerate(c)])
        k += len(c)
    js = ("'use strict';\n// generated by kit/make_timeline.py: film length, word timings (film seconds) and caption chunks\n"
          f"const FILM_DUR={dur:g};\nconst WT={json.dumps(wt)};\nconst CH={json.dumps(ch, ensure_ascii=False)};\n")
    (film / "timeline.js").write_text(js)
    print(f"timeline.js: {len(wt)} words, {len(ch)} chunks, narration {wt[0][1]:.2f}-{wt[-1][1]:.2f}s of {dur:g}s")


if __name__ == "__main__":
    main(Path(sys.argv[1]).resolve(), float(sys.argv[2]), float(sys.argv[3]) if len(sys.argv) > 3 else 0.25)
